#!/usr/bin/env python3
"""Markdown export of a guided tour (docs/plans/tutorial.md, deliverable 3). Stdlib + ImageMagick.

Renders a tour's chapters and step texts to Markdown, with one screenshot per step captured by the
real-input runner before the step's input (`tutorial_run.py --doc-shots`: doc-<id>.png and the
bubble / target rectangles in report.json). Each screenshot is cropped to the bubble and its target,
scaled to at most --width px and stored as a 256-colour PNG next to the Markdown file.

usage: export_md.py --tour resources/tutorials/bracket/tutorial.json --run build/tutorial-out/<run>
                    --out docs/tutorials/bracket.md [--width 760]
Without --run the Markdown is written without screenshots.
SPDX-License-Identifier: LGPL-2.1-or-later
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys

PAD = 48          # px around the bubble and the target
MIN = (720, 420)          # smallest crop: enough of the window around the target to find it
MIN_MODEL = (1200, 720)   # a face / edge / plane target: enough of the part to see where it is


def expand(text, timeline="FEATURES list", orientation="ViewCube"):
    """The bubble markup as Markdown: [[Key]] keycaps, {timeline} / {orientation} (the default
    layout's names, as TutorialEngine::expand); **bold** and `code` are Markdown already."""
    text = text.replace("{timeline}", timeline).replace("{orientation}", orientation)
    return re.sub(r"\[\[([^\]]+)\]\]", lambda m: "<kbd>%s</kbd>" % m.group(1), text)


def crop_box(doc, size, least=MIN):
    rects = [doc[k] for k in ("bubble", "target") if k in doc]
    w, h = size
    if not rects:
        return 0, 0, w, h
    x0 = min(r[0] for r in rects) - PAD
    y0 = min(r[1] for r in rects) - PAD
    x1 = max(r[0] + r[2] for r in rects) + PAD
    y1 = max(r[1] + r[3] for r in rects) + PAD
    # grow to the minimum size around the centre, then keep inside the screen
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    cw, ch = max(x1 - x0, least[0]), max(y1 - y0, least[1])
    cw, ch = min(cw, w), min(ch, h)
    x0 = min(max(0, cx - cw // 2), w - cw)
    y0 = min(max(0, cy - ch // 2), h - ch)
    return x0, y0, cw, ch


def magick():
    for tool in ("magick", "convert"):
        if shutil.which(tool):
            return tool
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tour", required=True)
    ap.add_argument("--run", help="a passing tutorial_run.py --doc-shots folder")
    ap.add_argument("--out", required=True)
    ap.add_argument("--width", type=int, default=760)
    args = ap.parse_args()
    with open(args.tour) as f:
        tour = json.load(f)
    shots, size = {}, (1600, 1000)
    if args.run:
        with open(os.path.join(args.run, "report.json")) as f:
            report = json.load(f)
        if not report.get("ok"):
            sys.exit("export_md: %s is not a passing run" % args.run)
        size = tuple(report.get("size", size))
        shots = {s["id"]: s["doc"] for s in report["steps"] if "doc" in s}
    tool = magick()
    stem = os.path.splitext(os.path.basename(args.out))[0]
    img_dir = os.path.join(os.path.dirname(os.path.abspath(args.out)), stem)
    if shots:
        if not tool:
            sys.exit("export_md: ImageMagick (magick or convert) is needed for the screenshots")
        shutil.rmtree(img_dir, ignore_errors=True)
        os.makedirs(img_dir)

    md = ["<!-- Generated by tools/tutorial/export_md.py from the tour file and a passing real-input run; "
          "do not edit by hand. -->", ""]
    md += ["# " + tour["title"], "", expand(tour.get("description", "")), ""]
    md += ["This is the printable copy of the in-app guided tour (**Help > Tutorials**). In the app a bubble points "
           "at each target and the tour moves on by itself when a step is done; here, follow the steps in order. "
           "Screenshots show the default layout (dark theme, FEATURES list, ViewCube).", ""]
    chapters = [c for c in tour["chapters"] if c["steps"]]
    md += ["## Contents", ""]
    for i, c in enumerate(chapters, 1):
        anchor = re.sub(r"[^a-z0-9 -]", "", ("%d. %s" % (i, c["title"])).lower()).replace(" ", "-")
        md.append("%d. [%s](#%s)" % (i, c["title"], anchor))
    md.append("")
    n = 0
    for i, c in enumerate(chapters, 1):
        md += ["## %d. %s" % (i, c["title"]), ""]
        for s in c["steps"]:
            n += 1
            md.append("**Step %d.** %s" % (n, expand(s["text"])))
            if s.get("hint"):
                md += ["", "> " + expand(s["hint"])]
            doc = shots.get(s["id"])
            if doc and os.path.exists(os.path.join(args.run, doc["png"])):
                model = str(s.get("anchor", "")).startswith("model:")
                x, y, w, h = crop_box(doc, size, MIN_MODEL if model else MIN)
                name = "step-%s.png" % s["id"].replace(".", "-")
                subprocess.run([tool, os.path.join(args.run, doc["png"]), "-crop", "%dx%d+%d+%d" % (w, h, x, y), "+repage",
                                "-resize", "%dx>" % args.width, "-strip", "-colors", "256", "PNG8:" + os.path.join(img_dir, name)],
                               check=True)
                md += ["", "![Step %d](%s/%s)" % (n, stem, name)]
            md.append("")
    if tour.get("finish"):
        md += ["## Done", "", expand(tour["finish"]), ""]
    with open(args.out, "w") as f:
        f.write("\n".join(md))
    print("export_md: %d steps, %d screenshots -> %s" % (n, len(shots), args.out))


if __name__ == "__main__":
    main()
